"""Drift, structure and safety-intent tests for the generated Colab notebooks.

control/vla_bridge/notebooks/ holds 13 notebooks + README.md generated by
scripts/build_colab_notebooks.py from scripts/colab_notebook_specs.py and the
control/vla_bridge sources. If any test here fails after an edit, run
`python scripts/build_colab_notebooks.py` from the repo root and commit the result.
"""
import hashlib
import importlib.util
import json
import re
from pathlib import Path

import pytest

from vla_bridge import backend_smoke

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
VLA_BRIDGE = ROOT / "control" / "vla_bridge"
NOTEBOOK_DIR = VLA_BRIDGE / "notebooks"
REGENERATE = "run python scripts/build_colab_notebooks.py"
CELL_ID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
EXPECTED_NAMES = {
    "fastfs_depth", "grpc_smolvla", "grpc_pi0", "grpc_pi05", "grpc_act", "grpc_diffusion",
    "grpc_groot_n17", "http_openvla_oft", "http_openvla", "http_octo", "http_wallx",
    "http_rdt1b", "http_groot_n15",
}


@pytest.fixture(scope="module")
def builder():
    monkeypatch = pytest.MonkeyPatch()
    monkeypatch.syspath_prepend(str(SCRIPTS))
    spec = importlib.util.spec_from_file_location("build_colab_notebooks",
                                                  SCRIPTS / "build_colab_notebooks.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    yield module
    monkeypatch.undo()


@pytest.fixture(scope="module")
def rendered(builder):
    return builder.render_all()


@pytest.fixture(scope="module")
def notebooks():
    return {path.stem: json.loads(path.read_text()) for path in sorted(NOTEBOOK_DIR.glob("*.ipynb"))}


def _text(cell):
    return "".join(cell["source"])


def _code_cells(notebook):
    return [cell for cell in notebook["cells"] if cell["cell_type"] == "code"]


def _is_embed(cell):
    return cell["cell_type"] == "code" and _text(cell).startswith("%%writefile ")


def test_committed_files_equal_generator_output(rendered):
    for path, text in rendered.items():
        assert path.exists(), f"{path} is missing: {REGENERATE}"
        assert path.read_text() == text, f"{path} drifted from the generator: {REGENERATE}"


def test_check_reports_nothing(builder):
    assert builder.check() == [], REGENERATE


def test_notebook_dir_holds_exactly_the_generated_files(rendered):
    on_disk = {path.name for path in NOTEBOOK_DIR.iterdir()}
    assert on_disk == {path.name for path in rendered}
    assert on_disk == {f"{name}.ipynb" for name in EXPECTED_NAMES} | {"README.md"}


def test_specs_cover_every_colab_hosted_backend(builder):
    backends = {spec["backend"] for spec in builder.specs.NOTEBOOKS if spec["lane"] != "depth"}
    depth = [spec for spec in builder.specs.NOTEBOOKS if spec["lane"] == "depth"]
    assert backends == set(backend_smoke.GRPC_LANE | backend_smoke.HTTP_LANE)
    assert [spec["name"] for spec in depth] == ["fastfs_depth"]
    assert {spec["backend"] for spec in builder.specs.NOTEBOOKS
            if spec["lane"] == "grpc"} == set(backend_smoke.GRPC_LANE)
    assert {spec["backend"] for spec in builder.specs.NOTEBOOKS
            if spec["lane"] == "http"} == set(backend_smoke.HTTP_LANE)


def test_notebook_structure(notebooks):
    assert set(notebooks) == EXPECTED_NAMES
    for name, notebook in notebooks.items():
        assert (notebook["nbformat"], notebook["nbformat_minor"]) == (4, 5), name
        assert notebook["metadata"]["kernelspec"]["name"] == "python3", name
        assert notebook["metadata"]["accelerator"] == "GPU", name
        ids = [cell["id"] for cell in notebook["cells"]]
        assert len(ids) == len(set(ids)), f"{name}: duplicate cell ids"
        assert all(CELL_ID.match(cell_id) for cell_id in ids), name
        for cell in _code_cells(notebook):
            assert cell["outputs"] == [], f"{name}:{cell['id']} has stored outputs"
            assert cell["execution_count"] is None, f"{name}:{cell['id']}"


def test_embedded_files_are_byte_identical_and_sha256_verified(notebooks):
    for name, notebook in notebooks.items():
        cells = notebook["cells"]
        for index, cell in enumerate(cells):
            if not _is_embed(cell):
                continue
            first, body = _text(cell).split("\n", 1)
            target = first.split()[1]
            assert target.startswith("/content/"), (name, target)
            repo_file = VLA_BRIDGE / Path(target).name
            assert body == repo_file.read_text(), f"{name}: {target} differs from {repo_file}"
            digest = hashlib.sha256(repo_file.read_bytes()).hexdigest()
            assert digest in _text(cells[index + 1]), f"{name}: no sha256 verify after {target}"


def test_every_notebook_embeds_the_server_helper(notebooks):
    for name, notebook in notebooks.items():
        embeds = [_text(cell).split("\n", 1)[0] for cell in notebook["cells"] if _is_embed(cell)]
        assert "%%writefile /content/colab_server_utils.py" in embeds, name


def test_every_launch_cell_stops_old_servers_and_waits_for_its_own(notebooks):
    for name, notebook in notebooks.items():
        launch = next(cell for cell in notebook["cells"] if cell["id"] == "launch")
        text = _text(launch)
        assert "stop_servers(" in text and "wait_until_ready(" in text, name
        assert "start_server(" in text and "'-u'" in text, name
        assert text.index("stop_servers(") < text.index("start_server(") < text.index(
            "wait_until_ready("), name


