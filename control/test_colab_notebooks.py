def test_every_notebook_has_diagnostics_and_teardown(notebooks, builder):
    for spec in builder.specs.NOTEBOOKS:
        cells = {cell["id"]: _text(cell) for cell in notebooks[spec["name"]]["cells"]}
        assert f"log_report({spec['log']!r})" in cells["diag-log"]
        assert f"process_report({spec['port']}, {spec['marker']!r}" in cells["diag-process"]
        assert "gpu_report()" in cells["diag-gpu"]
        if spec["tunnel"] == "http":
            assert f"health_report({spec['port']})" in cells["diag-health"]
        teardown = cells["teardown"]
        assert "ngrok.kill()" in teardown and "stop_server(" in teardown
        assert f"ngrok.disconnect({spec['tunnel_var']}.public_url)" in teardown


